import { AdapterErrorCode, VSRepoAdapterError } from "vsrepo";

export function validatePrismaClient(prisma: unknown, modelName: string, pkName: string): void {
    if (prisma == null) {
        throw new VSRepoAdapterError(
            "Missing Prisma client: the first constructor argument (prisma) is null/undefined.",
            AdapterErrorCode.MISSING_DB_CLIENT,
            null,
        );
    }

    const delegate = (prisma as any)[modelName];

    if (typeof delegate !== "object" || delegate === null) {
        throw new VSRepoAdapterError(
            `Invalid constructor config (modelName): no delegate found for '${modelName}' on the provided Prisma client ` +
                `(expected 'prisma.${modelName}' to exist — check that '${modelName}' matches a model name generated by Prisma).`,
            AdapterErrorCode.MODEL_NOT_FOUND,
            null,
        );
    }

    const fields = delegate.fields;

    if (typeof fields !== "object" || fields === null) {
        throw new VSRepoAdapterError(
            `Invalid Prisma client: 'prisma.${modelName}' has no 'fields' metadata, which the adapter needs to ` +
                `know the scalar fields of '${modelName}' (expected a Prisma 7 generated client delegate).`,
            AdapterErrorCode.MODEL_NOT_FOUND,
            null,
        );
    }

    if (!(pkName in fields)) {
        const available = Object.keys(fields)
            .map(name => `'${name}'`)
            .join(", ");

        throw new VSRepoAdapterError(
            `Invalid constructor config (pkName): no field '${pkName}' found on model '${modelName}' ` +
                `(expected 'pkName' to match a scalar field of '${modelName}' in your Prisma schema; ` +
                `available fields: ${available || "none"}).`,
            AdapterErrorCode.FIELD_NOT_FOUND,
            null,
        );
    }
}
