import { AdapterErrorCode, VSRepoAdapterError } from "vsrepo";

export function validatePrismaClient(prisma: unknown, modelName: string): void {
    if (prisma == null) {
        throw new VSRepoAdapterError(
            "Missing Prisma client: the first constructor argument (prisma) is null/undefined.",
            AdapterErrorCode.MISSING_DB_CLIENT,
            null,
        );
    }

    const delegate = (prisma as any)[modelName];

    if (typeof delegate !== "object" || delegate === null) {
        throw new VSRepoAdapterError(
            `Invalid constructor config (modelName): no delegate found for '${modelName}' on the provided Prisma client ` +
                `(expected 'prisma.${modelName}' to exist — check that '${modelName}' matches a model name generated by Prisma).`,
            AdapterErrorCode.MODEL_NOT_FOUND,
            null,
        );
    }
}
